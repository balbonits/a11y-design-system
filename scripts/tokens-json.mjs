// npm run tokens. Reads src/themes/registry.json and one src/themes/<id>.css per entry, then:
//  1. checks every theme defines the whole theme contract (scripts/theme-contract.mjs: Addendum 5 and 7),
//     and the R-2a component-layer rules (one level deep, contract names only, themes never set them),
//  2. writes src/tokens/themes.css (each theme's palette scoped to it; the first entry is also the
//     default when no data-theme is set),
//  3. writes src/tokens.json for non-CSS consumers and the contrast gate.
// Adding a theme = one token file + one registry entry. Nothing else names themes.
import fs from 'node:fs';
import { COLOR_TOKENS, EXTRA_TOKENS, SHAPE_TOKENS, TYPE_MOTION_TOKENS, componentLayerProblems, declsOf, parseTheme, registry, resolver } from './theme-contract.mjs';

const src = (f) => new URL(`../src/${f}`, import.meta.url);
const reg = registry();
if (!reg.length) throw new Error('registry.json is empty');
const ids = new Set();
let css = '/* GENERATED by `npm run tokens` from src/themes/registry.json. Do not edit; edit src/themes/<id>.css. */\n';
const themes = {}; const parsed = {};
const problems = [];
reg.forEach(({ id, label }, n) => {
  if (!/^[a-z][a-z0-9-]*$/.test(id) || !label) throw new Error(`bad registry entry ${JSON.stringify({ id, label })}`);
  if (ids.has(id)) throw new Error(`duplicate theme ${id}`); ids.add(id);
  const raw = fs.readFileSync(src(`themes/${id}.css`), 'utf8');
  const t = parseTheme(raw, id);
  parsed[id] = t;
  for (const k of [...SHAPE_TOKENS, ...TYPE_MOTION_TOKENS, ...EXTRA_TOKENS]) if (!(k in t.base)) problems.push(`${id}: missing ${k}`);
  for (const m of ['light', 'dark']) for (const k of COLOR_TOKENS) if (!(k in (m === 'dark' ? t.dark : t.light)) && !(k in t.base)) problems.push(`${id}.${m}: missing ${k}`);
  const sel = `[data-theme="${id}"]`;
  const scoped = raw.replace(/:root\s*\{/g, `${sel} {`);
  css += `\n/* ---- ${label} (${id})${n === 0 ? ', the default theme' : ''} ---- */\n` +
    (n === 0 ? scoped.split(sel).join(`:is(${sel}, :root:not([data-theme]))`) : scoped);
  const out = { label, default: n === 0, shape: {}, light: {}, dark: {}, reducedMotion: t.reduced };
  for (const m of ['light', 'dark']) { const r = resolver(t, m); for (const k of COLOR_TOKENS) out[m][k] = r(k); }
  const r = resolver(t, 'light');
  for (const k of [...SHAPE_TOKENS, ...TYPE_MOTION_TOKENS, ...EXTRA_TOKENS]) out.shape[k] = r(k);
  themes[id] = out;
});
const components = declsOf(fs.readFileSync(src('tokens/components.css'), 'utf8'));
problems.push(...componentLayerProblems(components, parsed));
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
fs.writeFileSync(src('tokens/themes.css'), css);
const json = { registry: reg, primitives: declsOf(fs.readFileSync(src('tokens/primitives.css'), 'utf8')), themes, components };
fs.writeFileSync(src('tokens.json'), JSON.stringify(json, null, 1) + '\n');
console.log(`tokens: ${reg.length} theme(s) [${reg.map((t) => t.id).join(', ')}], default ${reg[0].id}; ${Object.keys(json.components).length} component tokens`);
