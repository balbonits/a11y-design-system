"""Shared v3 token generator (rule of three: used by every v3 direction's gen.py).
build(dir, id, title, blurb, P, L, D, SHAPE, reduced, extra='', alias=None) writes tokens.json, tokens.css (R-2 shape) and TOKENS.md.
REGISTERED holds the registered extra color tokens: component tokens that alias a semantic color and default at the token layer,
so every theme resolves them and only a theme that differs overrides one (alias={'light':{...},'dark':{...}}, values are semantic names)."""
import json, os, re
REGISTERED={'dialog-border':'border'}  # CA ARCH-REVIEW Addendum 9: every dialog border reads var(--dialog-border); default var(--border).
def aliases(alias=None):
    alias=alias or {}
    return {m:{**REGISTERED,**alias.get(m,{})} for m in ('light','dark')}
def resolve(sem,id,A):
    """Adds each registered extra to tokens.json as its resolved color. Lint: fails unless it resolves to a hex color."""
    for m in ('light','dark'):
        t=sem[f'{id}-{m}']
        for k,v in A[m].items():
            t['--'+k]=t['--'+v]
            assert re.fullmatch(r'#[0-9A-Fa-f]{6}([0-9A-Fa-f]{2})?',t['--'+k]),f'{id}-{m} --{k} must resolve to a color'
def regtable(sem,id,A,sw=lambda h:''):
    head='''## Registered extra color tokens
Component tokens that alias a semantic color. The token layer gives each a default, so every theme resolves it, and a theme lists an override only where it differs (ARCH-REVIEW Addendum 9). The generator fails if one doesn't resolve to a color, and every dialog border reads `var(--dialog-border)`.

| Token | Default | Light | Dark |
|---|---|---|---|
'''
    rows=''
    for k in REGISTERED:
        l,dk=sem[f'{id}-light']['--'+k],sem[f'{id}-dark']['--'+k]
        rows+=f"| `--{k}` | `var(--{REGISTERED[k]})` | `var(--{A['light'][k]})` {sw(l)+' ' if sw(l) else ''}`{l}` | `var(--{A['dark'][k]})` {sw(dk)+' ' if sw(dk) else ''}`{dk}` |\n"
    return head+rows
def aliasblock(A,m):
    return '\n'.join(f'  --{k}: var(--{v});' for k,v in A[m].items())
def build(d, id, title, blurb, P, L, D, SHAPE, reduced, extra='', alias=None):
    A=aliases(alias)
    sem={f'{id}-light':{'--'+k:P[v] for k,v in L.items()},f'{id}-dark':{'--'+k:P[v] for k,v in D.items()}}
    resolve(sem,id,A)
    json.dump({'primitives':{'--palette-'+k:v for k,v in P.items()},'semantic':sem,'shape':SHAPE},open(os.path.join(d,'tokens.json'),'w'),indent=1)
    blk=lambda m:'\n'.join(f'  --{k}: var(--palette-{v});' for k,v in m.items())+'\n'+aliasblock(A,'light' if m is L else 'dark')
    css=f"""/* v3 direction {title}. R-2 shape: primitive -> semantic (Ember names). Generated by gen.py via ../shared/tokgen.py. */
:root {{
{chr(10).join(f'  --palette-{k}: {v};' for k,v in P.items())}
}}
[data-theme="{id}"] {{
{chr(10).join(f'  {k}: {v};' for k,v in SHAPE.items())}
}}
[data-theme="{id}"], [data-theme="{id}"][data-mode="light"] {{
{blk(L)}
  color-scheme: light;
}}
@media (prefers-color-scheme: dark) {{ [data-theme="{id}"]:not([data-mode]) {{
{blk(D)}
  color-scheme: dark;
}} }}
[data-theme="{id}"][data-mode="dark"] {{
{blk(D)}
  color-scheme: dark;
}}
@media (prefers-reduced-motion: reduce) {{ [data-theme="{id}"] {{
  {reduced}
}} }}
"""
    open(os.path.join(d,'tokens.css'),'w').write(css)
    sw=lambda h:f'<span style="display:inline-block;width:1em;height:1em;background:{h};border:1px solid #777;vertical-align:middle"></span>'
    rows=''.join(f'| `--{k}` | `{v}` | {sw(P[v])} `{P[v]}` | `{D[k]}` | {sw(P[D[k]])} `{P[D[k]]}` |\n' for k,v in L.items())
    reg=regtable(sem,id,A,sw)
    prim=''.join(f'| `--palette-{k}` | {sw(v)} `{v}` |\n' for k,v in P.items())
    md=f"""# {title}: token sheet

{blurb}

Live swatches for the current mode are in the prototype's [Tokens screen](index.html#tokens). Contrast results are in [CONTRAST.md](CONTRAST.md) (0 fails in light and dark).

## Semantic colors (R-2 names)
| Token | Light primitive | Light | Dark primitive | Dark |
|---|---|---|---|---|
{rows}
Color names are Ember's, plus `--highlight` and `--highlight-contrast` (a feature-band fill and the text on it) and `--focus-ring-color`, all from the locked set in ARCH-REVIEW Addendum 5. There are no `--radius` or `--focus` aliases.

{reg}
## Primitives
| Token | Value |
|---|---|
{prim}
## Shape, type and motion
Shape names follow ARCH-REVIEW Addendum 5 (`--radius-sm/md/lg/full`, `--border-width(-strong)`, `--shadow-raised/press`, `--divider-shape`, `--focus-ring-*`, `--control-*`, `--target-min`, `--tilt`, `--lift`). Anything else in this table is a direction-local extra (fonts, motion, and `--shadow-overlay` for floating layers) and is named as such in HANDOFF.md.

| Token | Value |
|---|---|
""" + ''.join(f'| `{k}` | `{v}` |\n' for k,v in SHAPE.items()) + '\n' + extra + '\n'
    open(os.path.join(d,'TOKENS.md'),'w').write(md)
